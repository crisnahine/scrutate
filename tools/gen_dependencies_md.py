#!/usr/bin/env python3
"""Generate docs/DEPENDENCIES.md: toolchain, direct dependencies with purpose and licence, and the
size of the transitive graph, from Cargo.toml + `cargo metadata --locked`."""
from __future__ import annotations

import json
import os
import subprocess
import sys

from third_party_notices import data_files

# The page head (banner and navigation); tools/gen_doc_assets.py --check compares it with its table.
DOC_HEAD = """<!-- Head written by tools/gen_doc_assets.py: edit its table, then run it. -->
<p align="center">
<picture>
<source media="(prefers-color-scheme: dark)" srcset="assets/banner-dependencies-dark.svg">
<img src="assets/banner-dependencies-light.svg" alt="Dependencies. Which crates and data are compiled in, and why?" width="880">
</picture>
</p>

# Toolchain and dependencies

[Documentation](README.md) &nbsp;·&nbsp; Previous: [Delivery index](DELIVERY.md) &nbsp;·&nbsp; Next: [Roadmap](ROADMAP.md)

<!-- End of head. -->
"""

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")

PURPOSE = {
    "aho-corasick": "multi-pattern prefilter for fuzzy search",
    "anyhow": "error type",
    "blake2": "token hashing (63-bit keys, same as the reference)",
    "clap": "command-line parsing",
    "clap_complete": "shell completions",
    "flate2": "zlib for chunk text and .npz (pure Rust backend)",
    "grep-matcher": "matcher trait shared with grep-searcher",
    "grep-regex": "regex matcher with line-oriented optimisations",
    "grep-searcher": "buffered/mmap line searching, context, binary detection",
    "grep-cli": "runs the system's decompression tools for `grep -z` (bzip2, xz, zstd, lz4, brotli, .Z)",
    "grep-pcre2": "PCRE2 matcher for `grep -P` (look-around, backreferences)",
    "tar": "tar archive members for `grep -z`",
    "zip": "zip archive members for `grep -z` (stored and deflate)",
    "half": "float16 semantic model weights",
    "ignore": "parallel, ignore-aware directory walking (a copy in vendor/ignore with four changes, listed in the workspace Cargo.toml)",
    "matrixmultiply": "sgemm for k-means (pure Rust)",
    "memchr": "newline and NUL scans when one large file is searched in ranges",
    "memmap2": "memory-mapped segments",
    "notify": "filesystem events for `watch` and `serve --watch` (inotify, ReadDirectoryChangesW; polling on macOS)",
    "proptest": "property-based tests (dev only)",
    "pyo3": "Python bindings (optional crate)",
    "rayon": "data parallelism (indexing, structural search)",
    "regex": "identifier/heuristic patterns",
    "regex-syntax": "pattern syntax trees: the text index's trigram conditions and the suffix literals of a regex",
    "rusqlite": "SQLite (bundled)",
    "unicode-normalization": "NFC form of names and non-ASCII words, so two spellings of one name match",
    "rust-stemmers": "Snowball English stemmer",
    "serde": "serialisation",
    "serde_json": "JSON output / MCP / config",
    "sha1": "file content hashes",
    "termcolor": "coloured terminal output",
    "toml": "configuration files",
    "tree-sitter": "incremental parsing runtime",
}


def main() -> int:
    meta = json.loads(subprocess.run(["cargo", "metadata", "--format-version", "1", "--locked"], cwd=ROOT, capture_output=True, text=True, check=True).stdout)
    pkgs = {p["id"]: p for p in meta["packages"]}
    core = next(p for p in meta["packages"] if p["name"] == "scrutate")
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    # transitive normal+build deps of the core
    seen, stack = set(), [core["id"]]
    while stack:
        nid = stack.pop()
        if nid in seen:
            continue
        seen.add(nid)
        for dep in nodes[nid]["deps"]:
            if any(k["kind"] in (None, "build") for k in dep["dep_kinds"]):
                stack.append(dep["pkg"])
    shipped = len(seen) - 1
    rustc = subprocess.run(["rustc", "--version"], capture_output=True, text=True).stdout.strip()
    out = [DOC_HEAD,
           f"Generated by `tools/gen_dependencies_md.py` from `Cargo.toml` and `cargo metadata --locked`.\n",
           "## Toolchain\n",
           f"- Built and tested with `{rustc}` (pinned in `rust-toolchain.toml`); minimum supported `rust-version` = {core['rust_version']}.",
           "- Edition 2021. Release profile: `opt-level=3`, fat LTO, `codegen-units=1`, no debug info, stripped.",
           "- Python ≥ 3.9 is needed only for the optional bindings, the reference implementation and the benchmark/test harnesses.\n",
           "## Direct dependencies of the `scrutate` crate\n",
           "| Crate | Version (locked) | Licence | Purpose | Optional |", "|---|---|---|---|---|"]
    # one row per crate: a crate declared twice (per target, with other features) is one dependency
    direct = sorted({d["name"]: d for d in core["dependencies"]}.values(), key=lambda d: d["name"])
    grammars = []
    for d in direct:
        if d["kind"] == "dev":
            continue
        locked = next((p for p in meta["packages"] if p["name"] == d["name"]), None)
        ver = locked["version"] if locked else d["req"]
        lic = (locked or {}).get("license") or "?"
        if d["name"].startswith("tree-sitter-"):
            grammars.append((d["name"], ver, lic, d["optional"]))
            continue
        out.append(f"| {d['name']} | {ver} | {lic} | {PURPOSE.get(d['name'], '')} | {'yes' if d['optional'] else ''} |")
    out.append(f"\n{len(grammars)} tree-sitter grammar crates ({sum(1 for g in grammars if not g[3])} default, {sum(1 for g in grammars if g[3])} behind `extra-langs`):\n")
    out.append("| Grammar crate | Version | Licence | Optional |")
    out.append("|---|---|---|---|")
    for n, v, l, o in grammars:
        out.append(f"| {n} | {v} | {l} | {'yes' if o else ''} |")
    out.append("\n## Data compiled into the binary\n")
    out.append("| Data | Version | Licence | Source | Purpose |")
    out.append("|---|---|---|---|---|")
    for d in data_files():
        out.append(f"| `{d['file']}` | Unicode {d['version']} | {d['license']} | {d['url']} | {d['purpose']} |")
    out.append(f"\n## Transitive graph\n\n{shipped} crates are compiled into the release binary (normal + build dependencies, dev dependencies excluded); "
               "the exact set with licences and purls is the SBOM produced by `tools/sbom.py` (CycloneDX 1.5). `cargo audit` result: see docs/TEST_RESULTS.md.\n")
    out.append("## Policy\n")
    out.append("- A dependency is added only with a written reason (what it replaces, size, maintenance, licence) and must be permissively licensed.\n"
               "- `Cargo.lock` is committed; CI builds with `--locked`; `cargo audit` runs on every push and the SBOM is attached to every release.\n"
               "- C code in the dependency tree: SQLite (bundled), tree-sitter runtime and grammars. No other native code; no networking crates.\n")
    with open(os.path.join(ROOT, "docs", "DEPENDENCIES.md"), "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote docs/DEPENDENCIES.md ({shipped} shipped crates)", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
