#!/usr/bin/env python3
"""Generate docs/LANGUAGES.md, the verified language capability registry, from the binary's own
registry (`scrutate languages --json`) joined with the snapshot test evidence
(crates/scrutate/tests/samples/expected.json, re-checked by `cargo test` on every build).

A capability is listed only when the registry declares it AND the sample for that language shows
the kind of symbol in question; anything else is marked as not verified.
"""
from __future__ import annotations

import json
import os
import re
import subprocess
import sys

# The page head (banner and navigation); tools/gen_doc_assets.py --check compares it with its table.
DOC_HEAD = """<!-- Head written by tools/gen_doc_assets.py: edit its table, then run it. -->
<p align="center">
<img src="assets/banner-languages.svg" alt="Languages. What does the index find in each language?" width="880">
</p>

# Language capability registry (verified)

[Documentation](README.md) &nbsp;·&nbsp; Previous: [Architecture](ARCHITECTURE.md) &nbsp;·&nbsp; Next: [Glossary](../GLOSSARY.md)

<!-- End of head. -->
"""

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
BIN = os.environ.get("SCRUTATE_BIN", os.path.join(ROOT, "target", "release", "scrutate"))
# optional: a build with `--features extra-langs`, so the optional grammars get rows of their own
EXTRA_BIN = os.environ.get("SCRUTATE_EXTRA_BIN")
SAMPLES = os.path.join(ROOT, "crates", "scrutate", "tests", "samples")
LANGS_RS = os.path.join(ROOT, "crates", "scrutate", "src", "langs.rs")

HEURISTIC_ONLY = {
    # languages covered by the keyword tier (no grammar in this build); sample -> note
    "sample.erb": "ERB / EJS templates (directive markup hides embedded definitions: windows only)",
    "sample.cr": "Crystal", "sample.nim": "Nim", "sample.pl": "Perl", "sample.sql": "SQL", "sample.txt": "plain text (windows)",
}


def header_rule() -> tuple[list[str], str]:
    """How `sniff` in langs.rs reads a `.h` file: the Objective-C markers and the C++ line pattern."""
    src = open(LANGS_RS).read()
    branch = re.search(r'ends_with\("\.h"\) \{\s*if \[([^\]]*)\]\.iter\(\)\.any\(\|k\| source\.contains\(k\)\) \{\s*"objc"\s*'
                       r'\} else if CPP_HEADER\.is_match\(source\) \{\s*"cpp"', src)
    pattern = re.search(r'static CPP_HEADER\b.*?r#"(.*?)"#', src, re.S)
    if not branch or not pattern:
        raise SystemExit(f"{LANGS_RS}: the .h rule of sniff no longer reads as expected; update header_rule")
    return re.findall(r'"([^"]*)"', branch.group(1)), pattern.group(1)


def marker_rule(ext: str, first: str) -> list[str]:
    """The texts `sniff` in langs.rs looks for in a file with `ext` before it reads it as `first`."""
    src = open(LANGS_RS).read()
    branch = re.search(r'ends_with\("' + re.escape(ext) + r'"\) \{\s*if \[([^\]]*)\]\.iter\(\)\.any\([^{]*\{\s*"' + first + '"', src)
    if not branch:
        raise SystemExit(f"{LANGS_RS}: the {ext} rule of sniff no longer reads as expected; update marker_rule")
    return re.findall(r'"([^"]*)"', branch.group(1))


def main() -> int:
    regs = json.loads(subprocess.run([BIN, "languages", "--json"], capture_output=True, text=True, check=True).stdout)
    default_ids = {r["id"] for r in regs}
    if EXTRA_BIN:
        regs = json.loads(subprocess.run([EXTRA_BIN, "languages", "--json"], capture_output=True, text=True, check=True).stdout)
    expected = json.load(open(os.path.join(SAMPLES, "expected.json")))
    extra = json.load(open(os.path.join(SAMPLES + "_extra", "expected.json")))
    sample_dir = {fn: "samples" for fn in expected}
    for fn, syms in extra.items():
        if fn not in expected:
            expected[fn], sample_dir[fn] = syms, "samples_extra"
    sample_by_ext: dict[str, str] = {}
    for fn in expected:
        ext = os.path.splitext(fn)[1] or fn
        sample_by_ext.setdefault(ext.lower(), fn)
        sample_by_ext.setdefault(fn, fn)
    out = []
    out.append(DOC_HEAD)
    out.append("Generated by `tools/gen_languages_md.py` from the binary's registry and the snapshot tests; "
               "regenerate after changing `crates/scrutate/src/langs.rs`.\n")
    out.append("## Tiers\n")
    out.append("1. **Grammar** (tree-sitter): definitions with kinds, qualified names, signatures, documentation, "
               "call edges and imports as listed per language below. Every row with a sample file is re-verified by "
               "`cargo test` (`tests/samples.rs` compares the parse of `tests/samples/<file>` with `expected.json`).\n"
               "2. **Heuristic**: languages without a grammar in this build get keyword-introduced definitions "
               "(`def`, `fn`, `function`, `sub`, `proc`, `class`, `struct`, `module`, Lisp `(def...`, SQL `CREATE ...`, "
               "shell `name() {`) with the indented block below them. No call edges or imports. A comment block "
               "right above a keyword definition is its documentation and ends the definition above it; the comment "
               "marks are the shared ones (`//`, `#`, `--`, `;`, `/* */`, `*`, `%`) plus, by extension, `(* *)` for "
               "ML, F#, TLA+ and Pascal, `{ }` for Pascal, `!` for Fortran (and `c` in column 1 for fixed form), "
               "`\"` for Vim, `{- -}` for the Haskell family, `<# #>` for PowerShell, `#| |#` for Lisp, `#[ ]#` for "
               "Nim, `/+ +/` for D and `%{ %}` for MATLAB. A custom language (a `[[language]]` table in the "
               "root's `.scrutate.toml` or in your configuration file, see [CLI](CLI.md#custom-languages)) is read "
               "this way too, with its own definition patterns and comment marks in place of the keywords and the "
               "shared marks.\n"
               "3. **Windows**: every other readable text file is indexed as overlapping 50-line windows, so it is "
               "searchable by Engine B (and, always, by Engine A). In the first two tiers the lines no definition's "
               "chunk keeps (code outside the definitions, the rest of a long one) are windows too, named after the "
               "definition or file they are part of.\n")
    out.append("Engine A (instant search) needs none of this: it searches every readable file of any language or no language.\n")
    out.append("## Grammar tier\n")
    out.append("| Language | Extensions / files | Definition kinds verified | Calls | Imports | Docstrings | Evidence |")
    out.append("|---|---|---|---|---|---|---|")
    n_verified = 0
    h_markers, h_pattern = header_rule()
    for r in sorted(regs, key=lambda x: x["id"]):
        exts = " ".join(r["extensions"] + r["filenames"])
        shared = " ".join(f"`{e}`" for e in r["extensions_by_content"])
        h_note = " (`.h`: see below)" if r["id"] == "c" else (" and " if exts else "") + shared + " by its content" if shared else ""
        optional = " (extra-langs)" if r["id"] not in default_ids else ""
        sample = None
        for e in r["extensions"]:
            if e.lower() in sample_by_ext:
                sample = sample_by_ext[e.lower()]
                break
        for f in r["filenames"]:
            if f in expected:
                sample = f
        # samples whose extension is shared with another language are named after the language
        for cand in (f"{r['id']}.{r['extensions'][0].lstrip('.')}" if r["extensions"] else "", {"matlab": "matrix.m", "puppet": "manifest.pp"}.get(r["id"], "")):
            if cand and cand in expected:
                sample = cand
        if sample:
            kinds = sorted({k for k, _ in expected[sample] if k not in ("module", "window")})
            kinds_s = ", ".join(kinds) if kinds else "(module only)"
            evidence = f"`tests/{sample_dir[sample]}/{sample}`"
            n_verified += 1
        else:
            kinds_s = "not verified by a sample"
            evidence = "registry only"
        out.append(f"| {r['id']}{optional} | {f'`{exts}`' if exts else ''}{h_note} | {kinds_s} | {'yes' if r['call_edges'] else 'no'} | {'yes' if r['imports'] else 'no'} | {'yes' if r['docstrings'] else 'no'} | {evidence} |")
    out.append("\nA `.h` file is read as objc when it holds " + ", ".join(f"`{m}`" for m in h_markers)
               + f", else as cpp when a line matches `{h_pattern}`, else as c (`sniff` in `crates/scrutate/src/langs.rs`).")
    listed = lambda marks: ", ".join(f"`{m}`" for m in marks)
    out.append("A `.m` file is read as objc when its first 4000 bytes hold " + listed(marker_rule(".m", "objc")) + ", else as matlab. "
               "A `.pp` file is read as pascal when it holds " + listed(marker_rule(".pp", "pascal"))
               + " and its first 4000 bytes hold no `$`, else as puppet.")
    n_opt = sum(r["id"] not in default_ids for r in regs)
    out.append(f"\n{len(regs) - n_opt} grammars in the default build" + (f", {n_opt} more with `--features extra-langs`" if n_opt else "")
               + f"; {n_verified} verified by snapshot samples. "
               "Call-edge and import extraction are declared per language by the registry rules; the sample for a language exercises them when its `expected.json` entry lists methods/functions and the file contains imports.\n")
    out.append("## Heuristic tier (samples in the snapshot test)\n")
    out.append("| Sample | Language | Definition kinds verified |")
    out.append("|---|---|---|")
    grammar_exts = {e.lower() for r in regs for e in r["extensions"] + r["extensions_by_content"]}
    for fn, lang in HEURISTIC_ONLY.items():
        # a sample a grammar reads belongs to the grammar table only
        if fn in expected and os.path.splitext(fn)[1].lower() not in grammar_exts:
            kinds = sorted({k for k, _ in expected[fn] if k not in ("module", "window")})
            out.append(f"| `{fn}` | {lang} | {', '.join(kinds) if kinds else '(windows only)'} |")
    out.append("\n## Optional grammars (`--features extra-langs`, +~80 MB of parse tables)\n")
    out.append("Off by default because of their size. Each has a sample in `crates/scrutate/tests/samples_extra/`, re-checked by "
               "`cargo test --features extra-langs --test samples_extra` against `expected.json` there.\n")
    out.append("| Sample | Symbols extracted (kind, qualified name) |")
    out.append("|---|---|")
    for fn in sorted(extra):
        syms = ", ".join(f"{k} `{q}`" for k, q in extra[fn] if k not in ("module", "window")) or "(module only)"
        out.append(f"| `{fn}` | {syms} |")
    out.append("")
    out.append("## Definitions written as assignments or under another owner\n")
    out.append("- Lua: a function assigned to a name (`local f = function`, `M.f = function`, `M[\"f\"] = function`) or given as "
               "a table field (`f = function` inside `local obj = {...}`) is a definition, owned by what holds it (`M.f`, `obj.f`). "
               "In a multiple assignment (`local a, M.b = function ... end, function ... end`) each function is a definition named "
               "by the target in its position.\n"
               "- JavaScript and TypeScript: a function assigned to a member is a definition: `Foo.prototype.bar = function` is the "
               "method `Foo.bar`, `Foo.make = () => ...` is `Foo.make`, `obj[\"k\"] = function` is `obj.k`, `exports.f` and "
               "`module.exports.f` are `f`, and `exports.a.b` is `a.b`. `this.x = function` inside a function or class is the method "
               "`x` of that function or class (`Widget.x`, `Panel.x` from its constructor). A default export written as an expression "
               "(`export default function () {}`, `export default class {}`, `module.exports = () => ...`) keeps its own name, or "
               "else takes the file's name (`app` for `lib/app.js`, the directory's name for an `index` file). The members of an "
               "object assigned to `module.exports` are definitions under their own names. A function stored under a computed key "
               "(`handlers[i] = function`) is not a definition. The comment above such an assignment is the function's documentation.\n"
               "- Julia: `function Base.show(...)` and `Base.show(...) = ...` are named `show` and owned by `Base`, so "
               "`symbol show` and `symbol Base.show` both find them; a method of a quoted operator, `Base.:(==)(a, b) = ...`, is "
               "named `==`.\n"
               "- C++: the call operator is named `operator()`. Haskell: an operator definition (`a <+> b = ...`, `(<+>) a b = ...`) "
               "is named by its operator. R: an R6 method in `R6Class(\"Counter\", public = list(add = function(n) ...))` is the "
               "method `Counter.add`.\n"
               "- GDScript: a file's `class_name` is a class whose chunk holds the `extends` line right below it and, when no "
               "member follows it at once, the comment block below the two, where Godot writes a class's documentation. The "
               "file is that class: its top-level definitions are the class's members (`Player.move`, a method), each its own "
               "chunk, and `symbol move` finds them by the bare name too. In a file without `class_name` they keep no owner "
               "(`move`, a function). An inner `class` owns its methods (`Player.Backpack.stash`). A `signal` is of kind "
               "`signal`, a `var` at file level or in an inner class body a `key`, a `const` there a `constant`, and a named "
               "`enum` an `enum`.\n"
               "- Ruby and Elixir names keep a trailing `?` or `!`, Julia names a `!`, R names their dots, Bash names their `::`, "
               "Haskell, OCaml, F# and Nix names their primes; a Rust raw identifier `r#type` is named `type`.\n")
    out.append("## Known limits\n")
    out.append("- Heuristic-tier languages get no call graph, no imports and approximate block extents.\n"
               "- Nesting depth of data keys (JSON/YAML/TOML) is capped at two levels.\n"
               "- Grammars that mis-parse unusual syntax fall back to the module header plus windows for that file (never to invented symbols).\n")
    path = os.path.join(ROOT, "docs", "LANGUAGES.md")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {path}: {len(regs)} grammars, {n_verified} verified", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
